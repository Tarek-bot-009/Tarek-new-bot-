module.exports.handleEvent = async function ({ api, event }) {
  const body = String(event.body || "").trim().toLowerCase();
  if (!body) return;
  if (body !== "shayri" && !body.startsWith("shayri ")) return;

  const line = SHAYRI[Math.floor(Math.random() * SHAYRI.length)];
  return api.sendMessage(line, event.threadID, event.messageID);
};

module.exports.run = async function ({ api, event }) {
  const line = SHAYRI[Math.floor(Math.random() * SHAYRI.length)];
  return api.sendMessage(line, event.threadID, event.messageID);
};
  
